# SpeechBrain's VoxCeleb verifier documents cosine similarity with a 0.25
# default operating point. Tune this for the deployment's audio environment.
SPEAKER_VERIFICATION_THRESHOLD = float(
    os.environ.get("SPEAKER_VERIFICATION_THRESHOLD", "0.25")
)
SPEAKER_MISMATCH_LIMIT = int(os.environ.get("SPEAKER_MISMATCH_LIMIT", "2"))
SPEAKER_PROFILE_CACHE_SECONDS = int(
    os.environ.get("SPEAKER_PROFILE_CACHE_SECONDS", str(2 * 60 * 60))
)
if not -1.0 <= SPEAKER_VERIFICATION_THRESHOLD <= 1.0:
    raise ValueError("SPEAKER_VERIFICATION_THRESHOLD must be between -1 and 1.")
if SPEAKER_MISMATCH_LIMIT < 2:
    raise ValueError("SPEAKER_MISMATCH_LIMIT must be at least 2.")
if SPEAKER_PROFILE_CACHE_SECONDS < 1:
    raise ValueError("SPEAKER_PROFILE_CACHE_SECONDS must be positive.")


